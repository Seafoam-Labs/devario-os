"""Generate the complete installer branding from one set of appearance tokens."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/calamares-theme"
DESTINATION = ROOT / "iso/airootfs/usr/share/calamares/branding/devario"


def render(source=SOURCE, variant=None, reduced_motion=None):
    tokens = json.loads((source / "tokens.json").read_text())
    selected = variant or tokens["variant"]
    palette = tokens["palettes"][selected]
    for value in palette.values():
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
            raise ValueError("Palette colors must be six-digit hex colors")
    theme = {key: tokens[key] for key in ("schemaVersion", "fontFamily", "fontPixelSize", "spacing", "cardRadius", "fieldRadius")}
    theme.update(variant=selected, palette=palette,
                 motionMs=0 if (tokens["reducedMotion"] if reduced_motion is None else reduced_motion) else tokens["motionMs"])
    values = {**theme, **palette, "assetPath": "@BRANDING_DIR@"}
    qss = (source / "stylesheet.qss.in").read_text()
    for key, value in values.items():
        qss = qss.replace(f"@{key}@", str(value))
    if re.search(r"@(?!BRANDING_DIR@)[A-Za-z]+@", qss):
        raise ValueError("Unresolved stylesheet token")
    desc = f'''# Generated by scripts/render-calamares-theme.py
# SPDX-License-Identifier: GPL-3.0-or-later
---
componentName: devario
welcomeStyleCalamares: false
welcomeExpandingLogo: false
windowExpanding: normal
windowSize: 1040px,700px
windowPlacement: center
sidebar: qml
navigation: widget
strings:
  productName: "Devario"
  shortProductName: "Devario"
  version: "${{VERSION_ID}}"
  shortVersion: "${{VERSION_ID}}"
  versionedName: "${{PRETTY_NAME}}"
  shortVersionedName: "Devario"
  bootloaderEntryName: "Devario"
  supportUrl: "https://fluxer.gg/vOjrMXcE"
  donateUrl: "https://www.patreon.com/SeafoamLabs"
images:
  productIcon: "mark.svg"
  productLogo: "mark.svg"
  productWelcome: "welcome.svg"
style:
  SidebarBackground: "{palette['surface']}"
  SidebarText: "{palette['secondary']}"
  SidebarTextCurrent: "{palette['onContainer']}"
  SidebarBackgroundCurrent: "{palette['primaryContainer']}"
slideshow: "show.qml"
slideshowAPI: 2
uploadServer:
  type: "none"
  url: ""
  sizeLimit: 0
'''
    files = {"branding.desc": desc, "stylesheet.qss": qss,
             "theme.json": json.dumps(theme, indent=2) + "\n",
             "Theme.js": "// Generated; SPDX-License-Identifier: GPL-3.0-or-later\n.pragma library\nvar theme = " + json.dumps(theme, indent=2) + ";\n"}
    for name in ("calamares-sidebar.qml", "show.qml"):
        files[name] = (source / name).read_text()
    files["chevron.svg"] = f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16"><path d="m4 6 4 4 4-4" fill="none" stroke="{palette["text"]}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>\n'
    files["mark.svg"] = f'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80" viewBox="0 0 80 80"><rect width="80" height="80" rx="24" fill="{palette["primaryContainer"]}"/><path d="M28 21h10c30 0 30 38 0 38H28z" fill="none" stroke="{palette["onContainer"]}" stroke-width="7" stroke-linejoin="round"/></svg>\n'
    files["welcome.svg"] = f'<svg xmlns="http://www.w3.org/2000/svg" width="320" height="150" viewBox="0 0 320 150"><rect x="20" y="15" width="280" height="120" rx="24" fill="{palette["low"]}"/><rect x="40" y="35" width="64" height="80" rx="16" fill="{palette["primaryContainer"]}"/><path d="M60 55h8c24 0 24 40 0 40h-8z" fill="none" stroke="{palette["onContainer"]}" stroke-width="5"/><rect x="124" y="44" width="150" height="10" rx="5" fill="{palette["primary"]}"/><rect x="124" y="66" width="116" height="8" rx="4" fill="{palette["outline"]}"/><rect x="124" y="92" width="76" height="22" rx="11" fill="{palette["primaryContainer"]}"/></svg>\n'
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=DESTINATION)
    parser.add_argument("--variant", choices=("dark", "light"))
    parser.add_argument("--reduced-motion", action="store_true", default=None)
    args = parser.parse_args()
    files = render(variant=args.variant, reduced_motion=args.reduced_motion)
    stale = []
    for name, content in files.items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(name)
        else:
            args.output.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Calamares theme is stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
